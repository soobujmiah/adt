/* ═══════════════════════════════════════════════════════════════
   ADT — geographic layer.

   A background map in the same visual language as the portfolio: real
   Natural Earth geometry, a Miller projection, restrained motion, and a
   static fallback when scripting or motion is unwelcome.

   It is an independent implementation with its own committed data
   (assets/geo/adt-geo.js, generated by tools/make-geo.py). Nothing is
   fetched from another site or repository at runtime.

   Geography rule (see tools/make-geo.py): the map states documented
   geography only. ADT is a single page, so its map holds ONE framed
   view — Dhaka and the South Asian context around it, the one place this
   project's evidence names. There is no camera flight, no scroll
   coupling and no second state: the only motion on the page is the
   pipeline rail, which is a diagram, not geography.

   With scripting off the map is simply not painted (`data-cam=""` keeps
   it hidden) and every section still reads: the map is decoration,
   never navigation.
   ═══════════════════════════════════════════════════════════════ */

(function () {
  'use strict';

  var G = window.ADT_GEO;
  var svg = document.querySelector('[data-map-svg]');
  var host = document.querySelector('[data-map]');
  if (!G || !svg || !host) return;

  var HALF = G.width / 2;
  var TOP = G.top;
  var BOTTOM = G.bottom;

  var reduceMotion =
    window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ── projection — the same maths the generator used offline ── */
  function millerY(latDeg) {
    var phi = (latDeg * Math.PI) / 180;
    return -1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * phi)) * (G.width / (2 * Math.PI));
  }
  function project(lon, lat) {
    return { x: ((lon + 180) / 360) * G.width, y: millerY(lat) };
  }

  /* ── paint the geometry ─────────────────────────────────────── */
  var NS = 'http://www.w3.org/2000/svg';
  function svgEl(name, attrs, cls) {
    var node = document.createElementNS(NS, name);
    Object.keys(attrs).forEach(function (k) { node.setAttribute(k, attrs[k]); });
    if (cls) node.setAttribute('class', cls);
    return node;
  }

  var landEl = host.querySelector('.geo-land');
  if (landEl) landEl.setAttribute('d', G.world);

  var countries = host.querySelector('.geo-countries');
  if (countries) {
    Object.keys(G.countries).forEach(function (iso) {
      countries.appendChild(
        svgEl('path', { d: G.countries[iso] },
          iso === 'BGD' ? 'geo-country geo-country-origin' : 'geo-country')
      );
    });
  }

  /* the origin mark — Dhaka, the one place the evidence names */
  var originGroup = host.querySelector('.geo-origin');
  if (originGroup) {
    originGroup.appendChild(svgEl('circle', { cx: G.origin.x, cy: G.origin.y, r: 6.5 }, 'geo-halo'));
    originGroup.appendChild(svgEl('circle', { cx: G.origin.x, cy: G.origin.y, r: 3.1 }, 'geo-ring'));
    originGroup.appendChild(svgEl('circle', { cx: G.origin.x, cy: G.origin.y, r: 1.7 }, 'geo-core'));
  }

  /* A signal leaving the origin into the page. These arcs are
     directional, not destinations: the far end claims no place, so no
     relationship is implied with anywhere ADT has no evidence for. */
  var flow = host.querySelector('.geo-flow');
  if (flow) {
    [[-150, -96], [128, -74], [96, 108]].forEach(function (d, i) {
      var to = { x: G.origin.x + d[0], y: G.origin.y + d[1] };
      var mx = (G.origin.x + to.x) / 2;
      var my = (G.origin.y + to.y) / 2 - 26;
      var path =
        'M' + G.origin.x.toFixed(1) + ' ' + G.origin.y.toFixed(1) +
        ' Q ' + mx.toFixed(1) + ' ' + my.toFixed(1) +
        ' ' + to.x.toFixed(1) + ' ' + to.y.toFixed(1);
      flow.appendChild(svgEl('path', { d: path }, i === 0 ? 'geo-arc geo-arc--primary' : 'geo-arc'));
      if (!reduceMotion) {
        var packet = svgEl('circle', { r: i === 0 ? 1.15 : 1 }, 'geo-packet');
        packet.appendChild(svgEl('animateMotion', {
          dur: (7 + i * 2.2) + 's',
          begin: (1.1 + i * 1.7) + 's',
          repeatCount: 'indefinite',
          path: path
        }));
        flow.appendChild(packet);
      }
    });
  }

  /* ── one fixed camera ───────────────────────────────────────────
     The framed view this page has always opened on: Dhaka plus the
     South Asian context around it. It is a constant, not a state, so
     nothing on the page can move it — no scroll handler, no
     intersection observer, no second source of camera truth. */
  var FIXED = { x: G.origin.x, y: G.origin.y + 6, hw: 105 };

  function clamp(cam) {
    var hw = cam.hw;
    var y;
    if (TOP + hw > BOTTOM - hw) y = (TOP + BOTTOM) / 2;
    else y = Math.min(Math.max(cam.y, TOP + hw), BOTTOM - hw);
    var over = hw * 0.25;
    var x = Math.min(Math.max(cam.x, hw - over), G.width - hw + over);
    return { x: x, y: y, hw: hw };
  }

  function boxOf(cam) {
    return (
      (cam.x - cam.hw).toFixed(1) + ' ' + (cam.y - cam.hw).toFixed(1) + ' ' +
      (cam.hw * 2).toFixed(1) + ' ' + (cam.hw * 2).toFixed(1)
    );
  }

  var cam = clamp(FIXED);
  var glow = host.querySelector('[data-map-glow]');

  function apply(next) {
    svg.setAttribute('viewBox', boxOf(next));
    if (glow) {
      glow.setAttribute('cx', next.x.toFixed(1));
      glow.setAttribute('cy', next.y.toFixed(1));
      glow.setAttribute('r', (next.hw * 1.05).toFixed(1));
    }
    host.setAttribute('data-cam', next.x.toFixed(1) + ',' + next.y.toFixed(1) + ',' + next.hw.toFixed(1));
  }

  apply(cam);

  /* ── the map is decoration: it stops when it cannot be seen ── */
  document.addEventListener('visibilitychange', function () {
    host.setAttribute('data-paused', document.hidden ? 'true' : 'false');
  });

  /* ── a one-off pulse when the pipeline section is reached ───── */
  var rail = document.querySelector('[data-pipeline]');
  if (rail && 'IntersectionObserver' in window) {
    var railIo = new IntersectionObserver(
      function (entries) {
        if (entries[0].isIntersecting) {
          rail.setAttribute('data-live', 'true');
          railIo.disconnect();
        }
      },
      { threshold: 0.35 }
    );
    railIo.observe(rail);
  } else if (rail) {
    rail.setAttribute('data-live', 'true');
  }
})();
